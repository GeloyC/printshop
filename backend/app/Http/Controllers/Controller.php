<?php

namespace App\Http\Controllers;

abstract class Controller
{
    /*
        conventional laravel method names:
        index() -- get a list of item
        show() -- get one item
        store() -- create an item
        update() -- update an item
        destroy() -- delete an item
    */

    /*
        This abstract controller is the base controller and will be inherited by other controllers that will be created in the future. 
    */
}
